"""
Standalone tool: convert a 2D boundary polygon (shapefile) into a single-face
OFF polygon, taking the Z of each vertex from the nearest point (in XY) of a
LAS point cloud.

The resulting .off can be used as ground polygon for mesh_gen
(city_iconic_mesh) in place of the convex hull generated by CityLODer.

Usage:
    python boundary_to_off.py <boundary.shp> <cloud.las> [output.off] [--ground-class N]

    --ground-class N   LAS class used for the Z projection (default: 2).
                       Use -1 to use all points (e.g. when the LAS is a DTM).

Notes:
    - The shapefile and the LAS must be in the same coordinate reference system.
    - If the shapefile holds several polygons, the largest one is used.
      Holes are ignored: only the exterior ring is exported.
"""

import argparse
import sys

import laspy
import numpy as np
import shapefile
from scipy.spatial import cKDTree


def signed_area(poly):
    x = poly[:, 0]
    y = poly[:, 1]
    return 0.5 * np.sum(x * np.roll(y, -1) - y * np.roll(x, -1))


def read_boundary(shp_path):
    """
    Return the exterior ring of the largest polygon in the shapefile as an
    (N, 2) array, CCW oriented, without the repeated closing vertex.
    """
    sf = shapefile.Reader(shp_path)

    rings = []
    for shp in sf.shapes():
        if not shp.points:
            continue
        pts = np.asarray(shp.points, dtype=np.float64)
        parts = list(shp.parts) + [len(pts)]
        for start, end in zip(parts[:-1], parts[1:]):
            ring = pts[start:end, :2]
            if len(ring) > 1 and np.allclose(ring[0], ring[-1]):
                ring = ring[:-1]
            if len(ring) >= 3:
                rings.append(ring)

    if not rings:
        raise ValueError(f"No polygon found in {shp_path}")

    # The exterior ring of the largest polygon is the one with the largest area
    ring = max(rings, key=lambda r: abs(signed_area(r)))

    # Ensure CCW orientation (shapefile exterior rings are CW)
    if signed_area(ring) < 0:
        ring = ring[::-1]

    return ring


def read_las_points(las_path, ground_class=2):
    """Read the XYZ points of the given class (all points if ground_class < 0)."""
    las = laspy.read(las_path)
    coords = np.vstack((las.x, las.y, las.z)).T.astype(np.float64)

    if ground_class < 0:
        return coords

    classification = np.asarray(las.classification)
    ground = coords[classification == ground_class, :]
    if len(ground) == 0:
        classes = ", ".join(map(str, np.unique(classification)))
        raise ValueError(
            f"No points with class {ground_class} in {las_path} "
            f"(classes found: {classes}). Use --ground-class -1 to use all points."
        )
    return ground


def project_on_las(ring2d, ground):
    """Assign Z to each 2D vertex from the nearest XY point of the cloud."""
    tree = cKDTree(ground[:, :2])
    dist, idx = tree.query(ring2d)
    return np.column_stack((ring2d, ground[idx, 2])), dist


def write_off(xyz, name_file="./ground_polygon.off"):
    """Write a single-face OFF polygon (translation of the MATLAB writer)."""
    n = xyz.shape[0]
    with open(name_file, "w") as f:
        f.write("%6s\n" % "OFF")
        f.write("%5d %5d %5d\n" % (n, 1, 0))
        for x, y, z in xyz:
            f.write("%12.8f %12.8f %12.8f\n" % (x, y, z))
        f.write("%5d " % n)
        for k in range(n):
            f.write("%5d " % k)
        f.write("\n")


def main():
    parser = argparse.ArgumentParser(
        description="Convert a 2D boundary shapefile into a ground polygon OFF, "
        "with Z projected from a LAS point cloud."
    )
    parser.add_argument("boundary", help="Boundary polygon shapefile (.shp)")
    parser.add_argument("las", help="LAS point cloud")
    parser.add_argument(
        "output", nargs="?", default="./ground_polygon.off", help="Output OFF file"
    )
    parser.add_argument(
        "--ground-class",
        type=int,
        default=2,
        help="LAS class used for Z (default: 2, -1 = all points)",
    )
    args = parser.parse_args()

    ring2d = read_boundary(args.boundary)
    print(f"Boundary vertices: {len(ring2d)}")

    ground = read_las_points(args.las, args.ground_class)
    print(f"Points used for Z projection: {len(ground)}")

    xyz, dist = project_on_las(ring2d, ground)
    print(
        f"XY distance boundary vertex -> nearest point: "
        f"max {dist.max():.2f}, mean {dist.mean():.2f}"
    )

    write_off(xyz, args.output)
    print(f"Written {args.output}")


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
